/*
 * Back-office strings, French and Arabic. French is the reference: the Arabic
 * dictionary must have exactly the same shape. Shared by server pages and
 * client components, so nothing here may touch cookies or the database.
 *
 * Amounts stay in Latin digits with a dot in both languages — the inputs
 * accept the same format, and it is what the tills and invoices print.
 */

export const langs = ["fr", "ar"] as const;
