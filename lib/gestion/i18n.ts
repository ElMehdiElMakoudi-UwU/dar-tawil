/*
 * Back-office strings, French and Arabic. French is the reference: the Arabic
 * dictionary must have exactly the same shape. Shared by server pages and
 * client components, so nothing here may touch cookies or the database.
 *
 * Amounts stay in Latin digits with a dot in both languages — the inputs
 * accept the same format, and it is what the tills and invoices print.
 */

export const langs = ["fr", "ar"] as const;
export type Lang = (typeof langs)[number];
export const defaultLang: Lang = "fr";

export const langDir: Record<Lang, "ltr" | "rtl"> = { fr: "ltr", ar: "rtl" };
export const langShort: Record<Lang, string> = { fr: "FR", ar: "عربي" };

export const isLang = (v: unknown): v is Lang => (langs as readonly unknown[]).includes(v);

/** Fills {placeholders} in a message template. */
export function fill(template: string, vars: Record<string, string | number> = {}) {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

